/**
 * Generate the theme CSS used by `example/index.html`.
 *
 * One @marianmeres/design-tokens bundled theme run through the Bootstrap Reboot
 * bridge: the output sets the `--app-color-*` design tokens (consumed by the
 * example's own stylesheet) AND the `--bs-*` variables (consumed by reboot.css).
 * Light mode lands on `:root`, dark mode on `:root.dark` — so light/dark is just
 * a class on `<html>`, no selector rewriting and no second file.
 *
 * Swap THEME for any name from `bundledThemeNames` and re-run:
 *   deno task example:themes
 */
import { generateThemedCss } from "jsr:@marianmeres/design-tokens@^1/reboot";
import { getBundledTheme } from "jsr:@marianmeres/design-tokens@^1/themes";

/** Which bundled theme to emit. */
const THEME = "slateTealOcean";

/** CSS variable prefix — generic, this is a standalone example. */
const PREFIX = "app-";

const schema = getBundledTheme(THEME);
if (!schema) throw new Error(`Unknown bundled theme "${THEME}"`);

const dir = new URL(".", import.meta.url).pathname;
const header = `/*
 * @marianmeres/design-tokens "${THEME}" theme + Bootstrap Reboot bridge.
 * Generated by example/themes/_generate.ts — do not edit by hand.
 * Light on :root, dark on :root.dark; prefix "${PREFIX}".
 */\n`;

await Deno.writeTextFile(
	`${dir}theme.css`,
	header + generateThemedCss(schema, PREFIX, { prettierIgnore: true }),
);

console.log(`Generated example/themes/theme.css from "${THEME}" (prefix "${PREFIX}").`);
